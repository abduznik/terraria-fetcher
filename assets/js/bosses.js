// Boss & Enemy Drops browser - inverts items[].sources[].from into a
// source -> [items] index, entirely client-side from the existing dataset.
(function () {
  const input = document.getElementById('bossSearchInput');
  const meta = document.getElementById('bossMeta');
  const results = document.getElementById('bossResults');

  let dropsBySource = new Map(); // normalized source name -> { displayName, drops: [{item, rate, quantity, modes}] }

  function escapeHtml(str) {
    return String(str).replace(/[&<>"']/g, c => ({
      '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;'
    }[c]));
  }

  function wikiIconUrl(name) {
    const file = name.trim().replace(/ /g, '_');
    return `https://terraria.wiki.gg/images/${encodeURIComponent(file)}.png`;
  }

  function normalize(str) { return (str || '').toLowerCase(); }

  function buildIndex(items) {
    const map = new Map();
    for (const item of items) {
      if (!item.sources) continue;
      for (const s of item.sources) {
        if (!s.from) continue;
        const key = normalize(s.from);
        if (!map.has(key)) map.set(key, { displayName: s.from, drops: [] });
        map.get(key).drops.push({
          item,
          rate: s.rate,
          quantity: s.quantity,
          modes: s.modes || []
        });
      }
    }
    return map;
  }

  function score(query, name) {
    if (name === query) return 1000;
    if (name.startsWith(query)) return 500 - name.length;
    const idx = name.indexOf(query);
    if (idx !== -1) return 200 - idx;
    return -1;
  }

  function search(query) {
    const q = normalize(query.trim());
    if (!q) return [];
    const scored = [];
    for (const [key, entry] of dropsBySource) {
      const s = score(q, key);
      if (s > 0) scored.push({ s, entry });
    }
    scored.sort((a, b) => b.s - a.s);
    return scored.slice(0, 20).map(x => x.entry);
  }

  function renderDropRow(d) {
    const item = d.item;
    const parts = [];
    if (d.rate) parts.push(`${escapeHtml(d.rate)} chance`);
    if (d.quantity && d.quantity !== '1') parts.push(`×${escapeHtml(d.quantity)}`);
    if (d.modes.length && d.modes.length < 3) parts.push(escapeHtml(d.modes.join(' / ')));
    return `
      <li class="drop-row">
        <span class="icon-slot" style="width:36px;height:36px;"><img src="${wikiIconUrl(item.name)}" alt="" loading="lazy" onerror="this.parentElement.style.visibility='hidden'"></span>
        <a href="tree.html?item=${encodeURIComponent(item.name)}">${escapeHtml(item.name)}</a>
        ${parts.length ? `<span class="tag" style="margin-left:auto;">${parts.join(' &middot; ')}</span>` : ''}
      </li>`;
  }

  function renderResults(list) {
    if (!list.length) {
      results.innerHTML = '<div class="empty">No boss or enemy found with that name. Try "Eye of Cthulhu", "Skeletron", "Golem", "Moon Lord"...</div>';
      return;
    }
    results.innerHTML = list.map(entry => `
      <div class="result-item">
        <div class="row">
          <div class="name-wrap">
            <span class="icon-slot"><img src="${wikiIconUrl(entry.displayName)}" alt="" loading="lazy" onerror="this.parentElement.style.visibility='hidden'"></span>
            <span class="name">${escapeHtml(entry.displayName)}</span>
          </div>
          <span class="tag">${entry.drops.length} drop${entry.drops.length === 1 ? '' : 's'}</span>
        </div>
        <ul class="ingredients drop-list">
          ${entry.drops.map(renderDropRow).join('')}
        </ul>
      </div>`).join('');
  }

  input.addEventListener('input', () => {
    const q = input.value;
    if (!q.trim()) {
      results.innerHTML = '';
      meta.textContent = `${dropsBySource.size.toLocaleString()} enemies/bosses/sources indexed. Start typing to search.`;
      return;
    }
    const matches = search(q);
    meta.textContent = `${matches.length} match${matches.length === 1 ? '' : 'es'}`;
    renderResults(matches);
  });

  fetch('data/items.json')
    .then(r => {
      if (!r.ok) throw new Error('HTTP ' + r.status);
      return r.json();
    })
    .then(data => {
      dropsBySource = buildIndex(data);
      meta.textContent = `${dropsBySource.size.toLocaleString()} enemies/bosses/sources indexed. Start typing to search.`;
    })
    .catch(err => {
      meta.textContent = 'Item database not found yet — it is generated by the "Fetch Terraria Data" GitHub Action. Run it from the Actions tab, then reload.';
      console.error(err);
    });
})();
